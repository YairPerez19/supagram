drop policy if exists "Supagram files are publicly readable" on storage.objects;
create policy "Supagram files are publicly readable"
  on storage.objects for select to anon, authenticated
  using (bucket_id = 'supagram');

drop policy if exists "Users can upload their own Supagram files" on storage.objects;
create policy "Users can upload their own Supagram files"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'supagram'
    and (storage.foldername(name))[1] in ('images', 'profile')
    and (storage.foldername(name))[2] = (select auth.uid())::text
  );

drop policy if exists "Users can update their own Supagram files" on storage.objects;
create policy "Users can update their own Supagram files"
  on storage.objects for update to authenticated
  using (
    bucket_id = 'supagram'
    and (storage.foldername(name))[1] in ('images', 'profile')
    and (storage.foldername(name))[2] = (select auth.uid())::text
  )
  with check (
    bucket_id = 'supagram'
    and (storage.foldername(name))[1] in ('images', 'profile')
    and (storage.foldername(name))[2] = (select auth.uid())::text
  );

drop policy if exists "Users can delete their own Supagram files" on storage.objects;
create policy "Users can delete their own Supagram files"
  on storage.objects for delete to authenticated
  using (
    bucket_id = 'supagram'
    and (storage.foldername(name))[1] in ('images', 'profile')
    and (storage.foldername(name))[2] = (select auth.uid())::text
  );
